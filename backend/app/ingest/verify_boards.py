"""Verify candidate board slugs against the real APIs and write data/companies.yaml.

python -m app.ingest.verify_boards [--keep 30]

A board is kept only if the API returns 200 with >= 1 job. Boards are ranked by how many
postings match our audience (tech roles that are intern/entry/new-grad, or in India/remote),
computed from the live response, never assumed.
"""

from __future__ import annotations

import argparse
import logging
from datetime import UTC, datetime

import yaml

from app.config import DATA_DIR
from app.ingest import classify
from app.ingest.sources import BoardNotFound, fetch_greenhouse, fetch_lever, greenhouse_board_name, make_client

log = logging.getLogger("getajob.verify")


def relevance(jobs) -> dict:
    tech = [j for j in jobs if classify.is_tech(j.title)]
    junior = [j for j in tech if classify.seniority(j.title) in ("intern", "new_grad", "entry")]
    india_remote = [
        j for j in tech if classify.in_india(j.location) or classify.is_remote(j.title, j.location, j.workplace_type)
    ]
    return {
        "total": len(jobs),
        "tech": len(tech),
        "tech_junior": len(junior),
        "tech_india_or_remote": len(india_remote),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--keep", type=int, default=30)
    args = ap.parse_args()
    cands = yaml.safe_load((DATA_DIR / "board_candidates.yaml").read_text())
    verified, skipped = [], []
    with make_client() as client:
        for source, slugs in cands.items():
            for slug in slugs:
                try:
                    if source == "greenhouse":
                        name = greenhouse_board_name(client, slug)
                        jobs = fetch_greenhouse(client, slug, name, content=False)
                    else:
                        jobs = fetch_lever(client, slug, slug)
                        name = slug  # Lever postings carry no company name; slug is the honest label
                except BoardNotFound:
                    skipped.append(f"{source}:{slug} 404")
                    continue
                except Exception as e:  # noqa: BLE001
                    skipped.append(f"{source}:{slug} error {type(e).__name__}")
                    continue
                if not jobs:
                    skipped.append(f"{source}:{slug} empty")
                    continue
                rel = relevance(jobs)
                verified.append({"source": source, "slug": slug, "company": name, **rel})
                print(f"ok   {source}:{slug:16} {rel}")
    for s in skipped:
        print("skip", s)
    verified.sort(key=lambda b: b["tech_junior"] * 3 + b["tech_india_or_remote"] * 2 + b["tech"] * 0.1, reverse=True)
    keep = [b for b in verified if b["tech"] > 0][: args.keep]
    out = {
        "verified_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "note": "Generated by app.ingest.verify_boards from live API responses. Counts are a snapshot.",
        "boards": keep,
    }
    (DATA_DIR / "companies.yaml").write_text(yaml.safe_dump(out, sort_keys=False), encoding="utf-8")
    print(f"\nverified {len(verified)}, kept {len(keep)}, skipped {len(skipped)} -> data/companies.yaml")


if __name__ == "__main__":
    logging.basicConfig(level="WARNING")
    main()
